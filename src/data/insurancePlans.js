export function getCategoryBySlug(slug) {
  return INSURANCE_CATEGORIES.find((c) => c.slug === slug);
}

export function getPlanById(planId) {
  for (const cat of INSURANCE_CATEGORIES) {
    const plan = cat.plans.find((p) => p.id === planId);
    if (plan) return { ...plan, category: cat };
  }
  return null;
}

export function getAllPlansFlat() {
  return INSURANCE_CATEGORIES.flatMap((cat) =>
    cat.plans.map((p) => ({ ...p, categorySlug: cat.slug, categoryName: cat.name, categoryIcon: cat.icon }))
  );
}
